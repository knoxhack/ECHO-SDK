def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def prepare_fixture_root(root: Path) -> Path:
    fixture_root = root / "build" / "echo-sdk-fixtures"
    resolved_fixture = fixture_root.resolve()
    try:
        resolved_fixture.relative_to((root / "build").resolve())
    except ValueError as exc:
        raise ValueError(f"Refusing to clean fixture output outside build/: {resolved_fixture}") from exc
    if fixture_root.exists():
        shutil.rmtree(fixture_root)
    fixture_root.mkdir(parents=True)
    write_text(
        fixture_root / "settings.gradle",
        "def echoBetaAddons = ['echosdkfixturecontent']\n"
        "def echoReleaseAddons = []\n",
    )
    write_text(
        fixture_root / "gradle.properties",
        "minecraft_version=26.1.2\n"
        "minecraft_version_range=[26.1.2,26.2)\n"
        "neo_version=26.1.2.29-beta\n"
        "mod_id=echosdkfixturehost\n"
        "mod_name=ECHO SDK Fixture Host\n"
        "mod_version=1.0.0\n"
        "mod_group_id=com.knoxhack.echo.sdk.fixturehost\n",
    )
    write_text(fixture_root / "build.gradle", "// ECHO SDK fixture root. Generated by validate_echo_sdk_templates.py.\n")
    write_text(fixture_root / "docs" / "echo" / "sdk" / "README.md", "# ECHO SDK Fixture\n")
    write_text(fixture_root / "core" / "echocore" / "build.gradle", "// ECHO SDK fixture echocore.\n")
    write_text(
        fixture_root / "core" / "echocore" / "gradle.properties",
        "mod_id=echocore\n"
        "mod_name=ECHO Core Fixture\n"
        "mod_version=1.0.0\n",
    )
    write_text(
        fixture_root / "core" / "echocore" / "src" / "main" / "resources" / "META-INF" / "echo.mod.json",
        json.dumps(
            {
                "schema": "echo.mod.v1",
                "id": "echocore",
                "name": "ECHO Core Fixture",
                "version": "1.0.0",
                "type": "core",
                "kind": "core",
                "role": "core",
                "official": True,
                "trustLevel": "official",
                "standalone": True,
                "side": "common",
                "requires": [],
                "optional": [],
                "provides": ["echo.core"],
                "consumes": [],
                "gameModes": [],
                "permissions": ["echo.core"],
                "assets": [],
                "transforms": [],
                "access": {},
                "apiStability": "stable",
            },
            indent=2,
            ensure_ascii=True,
        )
        + "\n",
    )
    return fixture_root


def render_fixture(root: Path, fixture_root: Path) -> list[str]:
    args = SimpleNamespace(
        module_id=FIXTURE_MODULE_ID,
        role="content_feature",
        kind_value=None,
        feature_id=None,
        class_name=None,
        display_name="ECHO SDK Fixture Content",
    )
    rendered = echo_sdk.render_template(
        root,
        "echo-addon-content",
        fixture_root,
        args,
        "addon",
        force=True,
        dry_run=False,
    )
    return [item.target.relative_to(fixture_root).as_posix() for item in rendered]


